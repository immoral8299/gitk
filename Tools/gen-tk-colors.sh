#
# Generates Sources/GitkCore/Settings/TkColorTable.swift from Tk's
# xlib/xcolors.c, the table Tk uses to resolve colour names.
#
# Usage: Tools/gen-tk-colors.sh [path/to/xcolors.c]
#
# Without an argument the file is downloaded from the pinned Tk tag into a
# temporary directory. Either way the file must match TK_SHA256, so the
# generated table always comes from the same source.
#
# xcolors.c stores each name as a 32-byte record. The grayNN and greyNN names
# are not all listed: gray1..gray8 are variants of the "gray" record, gray0 has
# its own record, and gray9..gray100 are computed with the formula from
# XParseColor in the same file.

set -eu

TK_TAG=core-9-0-3
TK_SHA256=2d998552a009e7e8a2154af3dc0ff5bff40f3118b078605801a0a41a5b7f5954
TK_URL="https://raw.githubusercontent.com/tcltk/tk/$TK_TAG/xlib/xcolors.c"

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/Sources/GitkCore/Settings/TkColorTable.swift"

tmp=$(mktemp -d "${TMPDIR:-/tmp}/gen-tk-colors.XXXXXX")
trap 'rm -rf "$tmp"' EXIT INT TERM

if [ "$#" -ge 1 ]; then
    src=$1
else
    src="$tmp/xcolors.c"
    curl -fsSL --retry 3 -o "$src" "$TK_URL"
fi

actual=$(shasum -a 256 "$src" | awk '{print $1}')
if [ "$actual" != "$TK_SHA256" ]; then
    echo "gen-tk-colors: $src has SHA-256 $actual, expected $TK_SHA256 ($TK_TAG)" >&2
    exit 1
fi

python3 -I - "$src" "$tmp/TkColorTable.swift" "$TK_TAG" <<'PY'
import re
import sys

src_path, out_path, tag = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(src_path, encoding="utf-8").read()
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)


def block(decl):
    start = text.index(decl)
    brace = text.index("{", start)
    end = text.index("\n};", brace)
    return text[brace + 1:end]


def value(token):
    if token.startswith("'"):
        return ord(token[1])
    return int(token, 0)


az = [int(x) for x in re.findall(r"\d+", block("static const unsigned char az[]"))]
records = re.findall(r"\{([^{}]*)\}", block("static const elem xColors[]"))

# az[r] is the index of the first record whose name starts with letter 'a' + r.
letters = {}
for r in range(len(az) - 1):
    for index in range(az[r], az[r + 1]):
        letters[index] = chr(ord("a") + r)

colors = {}


def add(name, rgb):
    key = name.lower()
    if key in colors and colors[key] != rgb:
        sys.exit("conflicting values for " + key)
    colors[key] = rgb


def gray_level(n):
    # Port of the special case in XParseColor (xcolors.c): num = n*255/100 rounded,
    # with 230 and 128 nudged down by one.
    num = (n * 255 + 50) // 100
    if num in (230, 128):
        num -= 1
    return (num, num, num)


for index, record in enumerate(records):
    tokens = [t.strip() for t in record.split(",") if t.strip()]
    if len(tokens) != 32 or not tokens[0].startswith("'"):
        continue  # placeholder rows such as {0xFF, 0, ...}
    values = [value(t) for t in tokens]
    letter = letters[index]
    chars = []
    for v in values[:28]:
        if v == 0:
            break
        chars.append(chr(v))
    name = letter + "".join(chars)
    main = (values[28], values[29], values[30])
    add(name, main)
    count = values[31]
    for n in range(1, count + 1):
        offset = 28 - 3 * n
        rgb = (values[offset], values[offset + 1], values[offset + 2])
        add(name + str(n), rgb)
    if name in ("gray", "grey"):
        for n in range(9, 101):
            add(name + str(n), gray_level(n))

if len(colors) < 600:
    sys.exit("only %d colours parsed; xcolors.c layout changed?" % len(colors))
for n in range(101):
    for base in ("gray", "grey"):
        if base + str(n) not in colors:
            sys.exit("missing " + base + str(n))

lines = [
    "// SPDX-License-Identifier: GPL-2.0-or-later",
    "// gitk-swift: a native macOS port of gitk.",
    "// Derived from gitk, Copyright © 2005-2016 Paul Mackerras and contributors.",
    "",
    "// Generated by Tools/gen-tk-colors.sh from Tk %s xlib/xcolors.c. Do not edit." % tag,
    "",
    "/// Colour names that Tk resolves, with their 8-bit RGB values.",
    "enum TkColorTable {",
    "    /// Packed 0xRRGGBB values keyed by lowercased name with spaces removed.",
    "    private static let packed: [String: UInt32] = [",
]
for key in sorted(colors):
    r, g, b = colors[key]
    lines.append('        "%s": 0x%02X%02X%02X,' % (key, r, g, b))
lines += [
    "    ]",
    "",
    "    /// Looks up a Tk colour name. Case and spaces are ignored, so \"light sky blue\"",
    "    /// and \"LightSkyBlue\" both resolve.",
    "    static func rgb(named name: String) -> (r: UInt8, g: UInt8, b: UInt8)? {",
    "        let key = name.lowercased().filter { $0 != \" \" }",
    "        guard let value = packed[key] else { return nil }",
    "        return (UInt8(value >> 16), UInt8((value >> 8) & 0xFF), UInt8(value & 0xFF))",
    "    }",
    "}",
    "",
]
with open(out_path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
PY

mkdir -p "$(dirname "$out")"
mv "$tmp/TkColorTable.swift" "$out"
echo "gen-tk-colors: wrote $out"
